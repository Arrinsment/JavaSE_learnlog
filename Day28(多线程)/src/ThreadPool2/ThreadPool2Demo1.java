package ThreadPool2;

import java.util.concurrent.*;

public class ThreadPool2Demo1 {
    public static void main(String[] args) {

        //这里去讲讲自定义线程池
        /*
         * 饭店故事 → 线程池参数对照表
         *
         * ┌────────────────────────────────┬────────────────────────────────┬──────────────────────────────┐
         * │ 饭店故事                        │ 线程池                          │ 说明                         │
         * ├────────────────────────────────┼────────────────────────────────┼──────────────────────────────┤
         * │ 正式员工数量                    │ 核心线程数量                    │ 正式工，不会轻易辞退          │
         * ├────────────────────────────────┼────────────────────────────────┼──────────────────────────────┤
         * │ 餐厅最大员工数                  │ 线程池中最大线程的数量          │ 正式工 + 临时工的总数上限     │
         * ├────────────────────────────────┼────────────────────────────────┼──────────────────────────────┤
         * │ 临时员工空闲多长时间被辞退（值）│ 空闲时间（值）                  │ 临时工多久没活干就被解雇      │
         * ├────────────────────────────────┼────────────────────────────────┼──────────────────────────────┤
         * │ 临时员工空闲多长时间被辞退（单位）│ 空闲时间（单位）               │ 秒、毫秒等时间单位            │
         * ├────────────────────────────────┼────────────────────────────────┼──────────────────────────────┤
         * │ 排队的客户                      │ 阻塞队列                        │ 客户（任务）太多，先排队等着  │
         * ├────────────────────────────────┼────────────────────────────────┼──────────────────────────────┤
         * │ 从哪里招人                      │ 创建线程的方式                  │ 通过线程工厂创建新线程        │
         * ├────────────────────────────────┼────────────────────────────────┼──────────────────────────────┤
         * │ 排队人数过多，超出顾客请下次再来│ 要执行的任务过多时的解决方案    │ 拒绝策略（拒绝新任务）        │
         * └────────────────────────────────┴────────────────────────────────┴──────────────────────────────┘
         */


        /*
         * ThreadPoolExecutor threadPoolExecutor = new ThreadPoolExecutor
         * (核心线程数量,最大线程数量,空闲线程最大存活时间,任务队列,创建线程工厂,任务的拒绝策略);
         *
         * 参数一：核心线程数量    不能小于0
         * 参数二：最大线程数    不能小于等于0，最大数量 >= 核心线程数量
         * 参数三：空闲线程最大存活时间    不能小于0
         * 参数四：时间单位    用TimeUnit指定
         * 参数五：任务队列    不能为null
         * 参数六：创建线程工厂    不能为null
         * 参数七：任务的拒绝策略    不能为null
         */


        //# 自定义线程池小结
        //
        //1. 创建一个空的池子
        //2. 有任务提交时，线程池会创建线程去执行任务，执行完毕归还线程
        //
        //不断的提交任务，会有以下三个临界点：
        //
        //1. 当核心线程满时，再提交任务就会排队
        //2. 当核心线程满，队伍满时，会创建临时线程
        //3. 当核心线程满，队伍满，临时线程满时，会触发任务拒绝策略

        ThreadPoolExecutor threadPoolExecutor=new ThreadPoolExecutor(
                3,//核心线程数量    不能小于0
                6,//最大线程数    不能小于等于0，最大数量 >= 核心线程数量(临时的线程数就是6-3)
                60,//空闲线程最大存活时间    不能小于0
                TimeUnit.SECONDS,//时间单位    用TimeUnit指定
                   new ArrayBlockingQueue<>(3),//任务队列    不能为null
                Executors.defaultThreadFactory(),//创建线程工厂    不能为null
                new ThreadPoolExecutor.AbortPolicy()//任务的拒绝策略    不能为null 这是匿名内部类的形式,必拒绝策略必须在线程池中才有意义

        );

        //接下来就是正常去提交任务即可
    //    threadPoolExecutor.submit();

    }
}
