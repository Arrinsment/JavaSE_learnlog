package ThreadPool2;

public class ThreadPoolDenmo2 {
    public static void main(String[] args) {

        // 向Java虚拟机返回可用处理器的数目
        int count = Runtime.getRuntime().availableProcessors();
        System.out.println(count);//16

        //这个方法会告诉你：你的电脑 CPU 能同时干多少件事。我的电脑是8核16线程就是可以同时(并行)16件事情
        //并发就是交替（轮流做），并行就是同时（一起做）

        /*
         * 线程池多大合适呢？
         *
         * ┌─────────────────────────────────────────────────────────────┐
         * │ CPU 密
         * 集型运算                                              │
         * │ 公式：最大并行数 + 1                                        │
         * │ 例如：8核 → 8 + 1 = 9                                       │
         * ├─────────────────────────────────────────────────────────────┤
         * │ I/O 密集型运算                                              │
         * │ 公式：最大并行数 × 期望CPU利用率 × (CPU计算时间+等待时间)/CPU计算时间 │
         * │ 例如：4核8线程，期望CPU利用率100%，CPU计算时间占比50%       │
         * │ 计算：8 × 100% × (100% / 50%) = 16                          │
         * ├─────────────────────────────────────────────────────────────┤
         * │ 举例：从本地文件中读取两个数据，并进行相加                  │
         * │ 操作一：读取两个数据（1秒）→ I/O操作                        │
         * │ 操作二：相加（1秒）→ CPU操作                                │
         * │ CPU计算时间占比 = 1 / (1+1) = 50%                           │
         * └─────────────────────────────────────────────────────────────┘
         *
         * thread dump（线程堆栈转储，用于查看线程状态）
         */
    }
}
