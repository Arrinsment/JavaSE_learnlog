    //这里去讲讲反射的基本概念

    //一:
    // ================== 反射 ==================
    // 一句话人话定义：
    // 反射就是：在程序运行的时候，去“折腾”类里面的构造方法、成员变量、成员方法。
    // 哪怕它们是私有的，也能拿出来用、改、调用。说白了,就是把类中的东西直接去调出来用
    // 官方定义：
    // 反射允许对成员变量、成员方法和构造方法的信息进行编程访问
    // ================== 反射能干什么 ==================
    //过程是先去获取,然后去解剖
    //然后这里获取Class
    // 1. 获取类的信息
    //    - 获取构造方法
    //    - 获取成员变量（字段）
    //    - 获取成员方法

    // 2. 解剖获取到的信息
    //    - 获取名字
    //    - 获取类型
    //    - 获取形参列表
    //    - 获取返回值类型（方法）
    //    - 获取修饰符（public、private等）
    //    - 获取注解

    // 3. 操作
    //    - 创建对象（调用构造方法）
    //    - 修改属性值（即使它是private）
    //    - 调用方法（即使它是private）
    //    - 抛出异常等

    // 一句话记忆：
    // 反射 = 运行时“扒开”类看个精光，想拿什么拿什么，想怎么改怎么改。





    //二:
    //详细讲解一下字节码文件,因为你要去反射 类,必须要经过字节码class
   /* 一个完整的比喻：从“想法”到“盖楼”
    我们以你写一个 Car 类为例
    ：
    你写源代码 (Car.java)：
    这就像是你在纸上画了一张汽车的设计草图。你在上面写：“这车要有引擎、四个轮子、能加速、能刹车”。这是给人（程序员）看的。

    编译成字节码 (Car.class)：
    你把设计草图交给工厂（JVM），工厂把它翻译成了一套施工蓝图和机器指令。这份蓝图不是给人看的，而是给工厂里的机器人和设备看的。它详细地标记了：“在内存的哪个位置放引擎，哪个位置放轮子，加速指令该怎么执行”。这就是字节码。它是一个标准化的、可执行的指令集。

    JVM 加载字节码，创建 Class 对象：
    当你要真正造车（运行程序）时，JVM 会把那份蓝图 (Car.class) 拿过来，仔仔细细地研究一遍。然后，它在自己的“脑子里”（内存中）建了一个超级详细的“车型目录”。
    这个目录里写着：“Car 类有一个引擎、四个轮子、两个方法（加速、刹车）……”。这个在内存里的“目录”，就是 Class 对象.(这个对象,你就可以去用里面的成员变量,构造方法,成员方法呀,里面都是有的,无论你是私有的还是怎么样的)
  */
   /* 这个比喻解释了你的疑惑
    你问的概念	对应比喻里的东西	一句话解释
    源代码 (Car.java)	你画的设计草图	给人看的，定义了这个类想做什么
    字节码 (Car.class)	机器施工蓝图	    给JVM 看的标准化指令，描述了类具体的结构
    Class 对象	JVM 内存中的“车型目录”	JVM 把蓝图读进脑子里后，创建的“活的说明书”，反射就是靠查这个说明书来操作类的。
    所以，“获取 Class 对象”是什么意思？
    获取 Class 对象，就相当于：
            “喂，JVM，把那个叫 Car 的车型目录给我拿来，我要查查它到底有几个轮子、怎么加速。”
    这就是 Class.forName("Car") 或 Car.class 或 car.getClass() 在做的事。
    总结一句话（这次真的不能再短了）
    字节码是 JVM 看懂的“施工图”，Class 对象是 JVM 把施工图加载到内存后创建的“活目录”。反射就是通过这个目录，在程序运行时去动态地查看和操作类的内部信息。
*/
  /*  字节码（.class文件）是编译后的中间代码。Class对象是JVM把字节码加载到内存后，为那个类创建的“档案卡”，记录了这个类的所有结构信息（方法、字段、构造器等）。
    反射就是通过这张“档案卡”来操作类的。*/
    //编译后 .class 存在硬盘上。运行时，JVM 把它加载到内存，并创建 Class 对象供你使用。(运行的时候,此时硬盘上的.class文件还是存在的,只是复制一份在内存上,
    // 他相当于创建了一个Class对象去把,内存中各种各样的字节,0和1,变成对象包裹起来,然后你要用反射,实际上就是去调用这个Class对象,因为这个对象什么都有)

    /*硬盘上的 Car.class 文件
        ↓
                【第1步：加载】
            ↓
    内存中的字节码（二进制数据）
            ↓
            【第2步：解析 + 创建对象】
            ↓
    Class 对象（你可以用的那个,因为这个Class对象,里面什么成员变量,构造方法,成员方法呀,里面都是有的）

*/
    //因为反射是从编译后,字节码的源头获取的,所以你类里面的所有东西应该都是可以得到的,无论是否被private修饰,因为他都可以得到,确实牛逼
    //反射不是从源代码入手，而是直接从编译后的字节码入手。字节码里有什么，反射就能拿什么。

    // ================== 获取Class对象的三种方式 ==================
    // 1. Class.forName("全类名");
    //    最常用，源头上获取，适合读取配置文件
    // 2. 类名.class
    //    最直接，通过类的静态属性获取
    // 3. 对象.getClass();
    //    最方便，通过已有对象获取

    // ================== 简单记忆 ==================
    //源代码阶段 ,Java文件A.java class文件 A.class
    //加载阶段  A.class
    //运行阶段  A A=new A()

   // 内存角度：
   // - 方式2、3：基于内存中已有的A.class字节码对象
   // - 方式1：从磁盘加载字节码文件到内存，再获取Class对象



