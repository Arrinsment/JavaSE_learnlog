        // 网络编程三要素

       // IP:
       // 设备在网络中的地址，是唯一的标识。
       // 端口号:
       // 应用程序在设备中唯一的标识。
       // 协议:
        // 数据在网络中传输的规则，常见的协议有 UDP、TCP、http、https、ftp。


        // 1. 网络编程三要素分别是什么？
        // IP、端口号、协议
        // 2. 网络编程三要素分别表示什么？
        // IP：设备在网络中的地址，是唯一的标识
        // 端口号：应用程序在设备中唯一的标识
        // 协议：数据在网络中传输的规则
        // 常见的协议有 UDP、TCP、http、https、ftp


        // IP
        // 全称：Internet Protocol，是互联网协议地址，也称IP地址。
        // 是分配给上网设备的数字标签。
        // 通俗理解
        // 上网设备在网络中的地址，是唯一的
        // 常见的IP分类为
        // IPv4、IPv6


        // IPv4
        // 全称：Internet Protocol version 4，互联网通信协议第四版。
        // 采用32位地址长度，分成4组
        // 32bit（4字节）
        // 11000000 10101000 00000001 01000010
        // 点分十进制表示法
        // 192.168.1.66


        // IPv4
        // 全称：Internet Protocol version 4，互联网通信协议第四版。
        // 采用32位地址长度，分成4组
        // 32bit（4字节）
        // 11000000101010000000000101000010
        // 点分十进制表示法
        // 192.168.1.66
        // 不够用了(256*256*256*256)
        // 2019年11月26日全部分配完毕

        // IPv4的地址分类形式
        // 1. 按使用场景分为两类
        // 公网地址：用于万维网（互联网）中，全球唯一，可直接对外通信
        // 私有地址：用于局域网内部，仅在组织/家庭内部使用，不能直接在互联网路由
        //
        // 2. 常见私有地址段说明
        // 192.168.0.0 -- 192.168.255.255 是最常见的C类私有地址段
        // 作用：为组织机构/家庭内部设备分配地址，避免占用公网IP，以此节省IPv4地址资源




        // IPv6
        // 全称：Internet Protocol version 6，互联网通信协议第六版。
        // 由于互联网的蓬勃发展，IP地址的需求量愈来愈大，而IPv4的模式下IP的总数是有限的。
        // 采用128位地址长度，分成8组。

        // 00100000 00000001
        // 00000000 00001000
        // 00000000 00010000
        // 00000000 00011000
        // 00000000 00011100
        // 00000000 00011110
        // 00000000 00100000
        // 00000000 00110000
        // 00000000 00110010
        // 00000000 00110011
        // 00000000 00111110
        // 00000000 00111111
        // 2^128
        // IPv6是2的128次方，可以给地球上的每一粒沙子都设置一个IP地址


       /* 特殊IP地址
        127.0.0.1，也可以是localhost：是回送地址也称本地回环地址，也称本机IP，永远只会寻找当前所在本机。
        建议：自己练习就写127.0.0.1
        127.0.0.1
      */


     /*   常用的CMD命令

      • ipconfig：查看本机IP地址
      • ping(后面接要去连通的具体Ip地址)：检查网络是否连通
   */


        // 端口号
        // 应用程序在设备中唯一的标识。
        // 端口号：由两个字节表示的整数，取值范围：0~65535
        // 其中0~1023之间的端口号用于一些知名的网络服务或者应用。
        // 我们自己使用1024以上的端口号就可以了。
        // 注意：一个端口号只能被一个应用程序使用。



        // 协议
        // 计算机网络中，连接和通信的规则被称为网络通信协议
        // OSI参考模型：世界互联协议标准，全球通信规范，但模型过于理想化，未能在因特网上进行广泛推广
        // TCP/IP参考模型（或TCP/IP协议）：事实上的国际标准。

        // OSI参考模型          TCP/IP参考模型      TCP/IP参考模型各层对应协议                      面向哪些
        // 应用层              应用层              HTTP、FTP、Telnet、DNS…                      一般是应用程序需要关注的，如浏览器、邮箱。程序员一般在这一层开发
        // 表示层              应用层              HTTP、FTP、Telnet、DNS…
        // 会话层              传输层              HTTP、FTP、Telnet、DNS…
        // 传输层              传输层              TCP、UDP、…                                  选择传输使用的TCP、UDP协议
        // 网络层              网络层              IP、ICMP、ARP…                               封装自己的IP、对方的IP等信息
        // 数据链路层          物理+数据链路层      硬件设备                                      转换成二进制利用物理设备传输
        // 物理层                                  010100101010100101010…



        // ================== 协议 ==================
        // 计算机网络中，连接和通信的规则被称为网络通信协议
        // ------------------ 两大参考模型 ------------------
        // OSI参考模型：世界互联协议标准，全球通信规范，但模型过于理想化，未能在因特网上广泛推广
        // TCP/IP参考模型（或TCP/IP协议）：事实上的国际标准


        // ------------------ TCP/IP参考模型分层 ------------------
        // 应用层
        //   - 协议：HTTP、FTP、Telnet、DNS等
        //   - 说明：一般是应用程序需要关注的，如浏览器、邮箱
        //   - 注：程序员一般在这一层开发

        // 传输层
        //   - 协议：TCP、UDP等
        //   - 说明：选择传输使用的TCP或UDP协议

        // 网络层
        //   - 协议：IP、ICMP、ARP等
        //   - 说明：封装自己的IP、对方的IP等信息



        // 协议
        // 计算机网络中，连接和通信的规则被称为网络通信协议

        // UDP协议
        // 全称：用户数据报协议（User Datagram Protocol）
        // 特点：面向无连接通信协议(不用确保网路是否链接,我只管传)
        // 优点：速度快
        // 缺点：有大小限制，一次最多发送64K，数据不安全，易丢失数据

        // TCP协议
        // 全称：传输控制协议（Transmission Control Protocol）
        // 特点：面向连接的通信协议(要确保网路链接成功,我只管传)
        // 优点：速度慢，没有大小限制，数据安全
        // 缺点：速度相对较慢
        // 物理+数据链路层
        //   - 协议：硬件设备
        //   - 说明：转换成二进制利用物理设备传输，如 010100101010100101010...









